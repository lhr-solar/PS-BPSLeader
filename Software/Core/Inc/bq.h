#pragma once
// Driver for BQ79616 chip. Section/table numbers refer to the datasheet in bq79616.pdf (SLUSF21A).

#include "common.h"
#include "UART.h"

#define BQ_UART_BAUD        1000000U    /* device supports 1 Mbps */

#define BQ_WAKE_TIM_HZ      1000000U    /* wake timer counts in 1 us ticks */
#define BQ_WAKE_PING_US     2750U       /* tHLD_WAKE 2.5-2.75, aim for the middle */
#define BQ_WAKE_SETTLE_MS   5U          /* Time to fully wake up, in MS*/
#define BQ_WAKE_PER_DEV_MS  10U         /* BQ79616 tSU(WAKE_SHUT) max, per stack device (bq79616.pdf Section 5.6) */
#define BQ_MAX_DEVICES      4U          /* max BQ79616s in the stack, not counting the BQ79600 bridge */
#define BQ_NUM_CELLS        8U          /* cells in series on each BQ79616, 6-16 (ACTIVE_CELL) */

_Static_assert(BQ_NUM_CELLS >= 6U && BQ_NUM_CELLS <= 16U, "BQ79616 supports 6S to 16S");

#define BQ_MAX_WRITE_LEN    8U      /* DATA_SIZE field is 3 bits            */
#define BQ_MAX_DATA_LEN     128U    /* RESPONSE_BYTE field is 7 bits        */
#define BQ_MAX_DEV_ADDR     0x3FU
#define BQ_RESP_TIMEOUT_MS  10U     /* max wait between response bytes     */

#define BQ_MAX_FRAME_LEN    (1U + 1U + 2U + BQ_MAX_DATA_LEN + 2U)

typedef enum {
    BQ_OK = 0,
    BQ_ERR
} bq_status_t;

typedef struct bq_init_struct_t {
    uint16_t tx_pin;
    uint16_t rx_pin;
    GPIO_TypeDef* tx_rx_port;
    uint16_t fault_pin;
    GPIO_TypeDef* fault_port;

    UART_HandleTypeDef* huart;      // Sharepoint UART handle wired to the BQ, e.g. husart3
    uint8_t uart_af;                // AF that routes tx/rx to huart, e.g. GPIO_AF7_USART3

    // The WAKE ping is generated by a timer channel output on tx_pin, so tx_pin
    // must have one of TIM2..TIM5's channels as an alternate function.
    // e.g. PB10: TIM2, TIM_CHANNEL_3, GPIO_AF1_TIM2
    TIM_TypeDef* wake_tim;
    uint32_t wake_tim_channel;      // TIM_CHANNEL_1..TIM_CHANNEL_4
    uint8_t wake_tim_af;

    uint8_t num_devices;            // BQ79616s in the stack (0..BQ_MAX_DEVICES), not counting the bridge
} bq_init_struct_t;

/* Command frame REQ_TYPE (INIT byte bits 6:4), datasheet Table 7-10 */
typedef enum {
    BQ_SINGLE_READ      = 0,
    BQ_SINGLE_WRITE     = 1,
    BQ_STACK_READ       = 2,
    BQ_STACK_WRITE      = 3,
    BQ_BROAD_READ       = 4,
    BQ_BROAD_WRITE      = 5,
    BQ_BROAD_WRITE_REV  = 6,
} bq_req_t;

// One device's response to a read: the DEV ADR it sent back and the register bytes
typedef struct bq_response_frame_t {
    uint8_t dev_addr;
    uint8_t data[BQ_MAX_DATA_LEN];
} bq_response_frame_t;

// A command to the BQ chain, passed to bq_write() and bq_read()
typedef struct bq_msg_frame_t {
    bq_req_t req;
    uint8_t dev_addr;               // only used for single read/write
    uint16_t reg_addr;              // first register
    const uint8_t *data;            // write: the bytes to write. read: unused, may be NULL
    uint8_t len;                    // write: bytes in data (1-8). read: bytes to read per device (1-128)
} bq_msg_frame_t;


// inits the peripherals for the bq chip (CRC unit, UART, wake timer, pins). Does not wake the chip.
bq_status_t bq_init(const bq_init_struct_t init);

// sends a WAKE ping (RX low for BQ_WAKE_PING_US). Must be called from a task after
// bq_init(), since it blocks with vTaskDelay. Fails if a frame is still sending.
bq_status_t bq_wake(void);

// send a write command. msg->req must be one of the write types
bq_status_t bq_write(const bq_msg_frame_t *msg);

// Largest number of frames a read can return: a broadcast read gets one from every BQ79616 plus the bridge
#define BQ_MAX_RESPONSE_FRAMES  (BQ_MAX_DEVICES + 1U)

// send a read command (msg->req one of the read types) and collect the replies into the caller's
// frames array, which holds max_frames entries. A read returns 1 frame for a single read,
// num_devices for a stack read (top of stack first), num_devices + 1 for a broadcast read (bridge
// last). Returns BQ_ERR without sending anything if max_frames is too small; an array of
// BQ_MAX_RESPONSE_FRAMES always fits. On BQ_ERR the array's contents are undefined.
bq_status_t bq_read(const bq_msg_frame_t *msg, bq_response_frame_t *frames, uint8_t max_frames);

// assigns address 0 to the BQ79600 and 1..num_devices to the BQ79616s (top of stack last), then
// reads the addresses back to check them (bq79600-q1.pdf Table 7-9). Run right after bq_wake(),
// from a task. Needs num_devices >= 1.
bq_status_t bq_auto_address(void);

// configures every BQ79616 with a stack write, then reads each register back from every device:
//   ACTIVE_CELL: BQ_NUM_CELLS cells in series
//   COMM_TIMEOUT_CONF: long comm timeout of 1 min, then SHUTDOWN; short comm timeout off
//   GPIO_CONF1..4: GPIO1-8 as ADC-only thermistor inputs (no OT/UT comparators)
//   CONTROL2: TSREF on, to bias the thermistor dividers, then waits for it to settle
// These are OTP-shadowed registers that a digital reset (including a WAKE) puts back to their
// OTP values, so run this after every bq_wake() + bq_auto_address(), from a task.
bq_status_t bq_config(void);

// runs one single-shot main ADC round robin on every BQ79616 and reads cells 1..BQ_NUM_CELLS
// into cell_voltages_mv[dev - 1][cell - 1], in mV (device 1 is the bottom of the stack). Integer
// maths only; a negative reading is reported as 0 mV. Rows past num_devices are left untouched.
// Run after bq_config(), from a task.
bq_status_t bq_read_cell_voltages(uint16_t cell_voltages_mv[BQ_MAX_DEVICES][BQ_NUM_CELLS]);




// REGISTERS
#define BQ_REG_CONTROL1 (0x0309)
#define BQ_REG_CONTROL1_SEND_WAKE (1 << 5)
#define BQ_REG_CONTROL1_ADDR_WR (1 << 0)
#define BQ_REG_DIR0_ADDR (0x0306)
#define BQ_REG_COMM_CTRL (0x0308)          /* BQ79616 only */
#define BQ_REG_COMM_CTRL_TOP_STACK (1 << 0)
#define BQ_REG_COMM_CTRL_STACK_DEV (1 << 1)
#define BQ_REG_OTP_ECC_DATAIN1 (0x0343)    /* DATAIN1..8 are the auto-addressing DLL sync dummies */
#define BQ_REG_OTP_ECC_DATAIN8 (0x034A)
#define BQ_REG_DEV_CONF1 (0x2001)          /* BQ79600 only */
#define BQ_REG_DEV_CONF1_RESET (0x14)
#define BQ_REG_BRIDGE_PARTID (0x2120)    /* BQ79600 only: silicon revision, 0x00 = A0 (bq79600-q1.pdf Section 7.5.22) */
#define BQ_REG_PARTID (0x0500)           /* BQ79616 only (bq79616.pdf Section 6.5.4.2.1) */
#define BQ_REG_PARTID_BQ79616 (0x21)
#define BQ_REG_CUST_MISC1 (0x0021)       /* BQ79616 only: CUST_MISC1..8 scratch pad, 0x0021-0x0028 (bq79616.pdf Section 6.5.4.1.3) */
#define BQ_REG_ACTIVE_CELL (0x0003)       /* BQ79616 only (bq79616.pdf Section 6.5.4.3.2) */
#define BQ_REG_ACTIVE_CELL_NUM(cells) ((uint8_t)((cells) - 6U))    /* NUM_CELL: 0x0 = 6S ... 0xA = 16S */
#define BQ_REG_COMM_TIMEOUT_CONF (0x0019) /* BQ79616 only (bq79616.pdf Section 6.5.4.3.6) */
#define BQ_REG_COMM_TIMEOUT_CONF_CTL_ACT_SHUTDOWN (1 << 3)          /* long timeout -> SHUTDOWN, not SLEEP */
#define BQ_REG_COMM_TIMEOUT_CONF_CTL_TIME_1MIN (0x4)               /* CTL_TIME[2:0] = 100 */
#define BQ_REG_GPIO_CONF1 (0x000E)        /* BQ79616 only: GPIO_CONF1..4 = 0x000E..0x0011 (bq79616.pdf Section 6.5.4.9) */
#define BQ_REG_GPIO_CONF4 (0x0011)
#define BQ_GPIO_MODE_ADC_ONLY (0x2)       /* GPIOn[2:0] = 010 */
#define BQ_REG_GPIO_CONF_PAIR(odd, even) ((uint8_t)(((even) << 3) | (odd)))  /* odd GPIO in [2:0], even in [5:3] */
#define BQ_REG_CONTROL2 (0x030A)          /* bq79616.pdf Section 6.5.4.3.12 */
#define BQ_REG_CONTROL2_TSREF_EN (1 << 0)
#define BQ_TSREF_SETTLE_MS      10U         /* tTSREF_ON is 6 ms with CTSREF = 1 uF (Section 5.6); more C needs longer */
#define BQ_REG_ADC_CTRL1 (0x030D)         /* BQ79616 only (bq79616.pdf Section 6.5.4.5.7) */
#define BQ_REG_ADC_CTRL1_MAIN_MODE_SINGLE (0x1)                     /* 8 round robins, then stop */
#define BQ_REG_ADC_CTRL1_MAIN_MODE_CONT (0x2)                       /* round robin until stopped */
#define BQ_REG_ADC_CTRL1_MAIN_GO (1 << 2)
#define BQ_REG_ADC_STAT1 (0x0527)         /* BQ79616 only (bq79616.pdf Section 6.5.4.4.2) */
#define BQ_REG_ADC_STAT1_DRDY_MAIN (1 << 0)
#define BQ_REG_VCELL_HI(cell) ((uint16_t)(0x0586U - 2U * ((cell) - 1U)))   /* VCELL1_HI = 0x0586 ... VCELL16_HI = 0x0568 */

#define BQ_VCELL_UV_PER_LSB_X100 19073      /* VLSB_ADC = 190.73 uV/LSB, x100 to stay integer (bq79616.pdf Section 5) */
#define BQ_ADC_RESULT_INVALID   ((int16_t)0x8000)   /* result register reset value: not converted yet */
#define BQ_AFE_SETTLE_MS        4U          /* tAFE_SETTLE, after ACTIVE or a NUM_CELL change (Section 6.3.2.1.3.1) */
#define BQ_ADC_SINGLE_RUN_MS    2U          /* single run is 8 x tMAIN_ADC_CYCLE (192 us) = 1.536 ms */
